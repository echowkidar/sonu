/** A work request with the tracker's typed columns and the computed columns, ready to write or summarise. */
export interface MasterRow extends ComputedColumns {
  wrCode: string;
  dateRequested: IsoDate | null;
  dateTradeAssigned: IsoDate | null;
  requestor: string | null;
  siteCode: string | null;
  siteName: string | null;
  buildingCode: string | null;
  buildingName: string | null;
  problemType: string | null;
  description: string | null;
  wrStatus: string | null;
  priority: string | null;
  workTeamCode: string | null;
  estimatedTotalCost: number | null;
  targetDate: IsoDate | null;
  /** Contractor status (one of the 15) typed by people; null = not set. */
  status: string | null;
  fcRemarks: string | null;
}

/**
 * Join the rows of Pending Work Requests with the tracker's typed columns and compute everything.
 * `rfeLookup` comes from Review Approved Estimations (WR code -> submitted / approved dates).
 */
export function buildMasterRows(
  pendingRows: TypedRow[],
  opts: {
    today: IsoDate;
    rfeLimitDays?: number;
    rfeLookup?: RfeLookup;
    lookups?: Lookups;
    typed?: Map<string, { status: string | null; fcRemarks: string | null }> | Record<string, { status: string | null; fcRemarks: string | null }>;
  },
): MasterRow[] {
  const get = (code: string) => (opts.typed instanceof Map ? opts.typed.get(code) : opts.typed?.[code]);
  return pendingRows.map((r) => {
    const s = (k: string) => (r[k] === undefined || r[k] === null ? null : String(r[k]));
    const typed = get(String(r.wrCode));
    const fcRemarks = typed?.fcRemarks ?? null;
    const wr = {
      wrCode: String(r.wrCode),
      wrStatus: s('wrStatus'),
      dateRequested: s('dateRequested'),
      dateTradeAssigned: s('dateTradeAssigned'),
      targetDate: s('targetDate'),
      estimatedTotalCost: typeof r.estimatedTotalCost === 'number' ? r.estimatedTotalCost : null,
      siteCode: s('siteCode'),
      problemType: s('problemType'),
      fcRemarks,
    };
    const computed = computeColumns(wr, { today: opts.today, rfeLimitDays: opts.rfeLimitDays, rfeLookup: opts.rfeLookup, lookups: opts.lookups });
    return {
      wrCode: wr.wrCode,
      dateRequested: wr.dateRequested,
      dateTradeAssigned: wr.dateTradeAssigned,
      requestor: s('requestor'),
      siteCode: wr.siteCode,
      siteName: s('siteName'),
      buildingCode: s('buildingCode'),
      buildingName: s('buildingName'),
      problemType: wr.problemType,
      description: s('description'),
      wrStatus: wr.wrStatus,
      priority: s('priority'),
      workTeamCode: s('workTeamCode'),
      estimatedTotalCost: wr.estimatedTotalCost,
      targetDate: wr.targetDate,
      status: typed?.status ?? null,
      fcRemarks,
      ...computed,
    };
  });
}

const isoToDate = (iso: string | null): Date | null => (iso ? new Date(`${iso}T00:00:00Z`) : null);

const HEADER_FILL: ExcelJS.Fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1F3A5F' } };
const HEADER_FONT: Partial<ExcelJS.Font> = { bold: true, color: { argb: 'FFFFFFFF' } };

function styleHeader(row: ExcelJS.Row) {
  row.eachCell((c) => {
    c.fill = HEADER_FILL;
    c.font = HEADER_FONT;
    c.alignment = { vertical: 'middle', wrapText: true };
  });
}

/**
 * The "Master" workbook in the tracker's layout. Sheets:
 *  - "Status": title on row 1, captions on row 2, one row per WR, columns as in analysis 07 (Marafiq columns,
 *    Status, FC Remarks, then the computed columns written as VALUES, not formulas, so every reader sees the same numbers).
 *  - "Statistics": facility x contractor status.
 *  - "Summary": discipline x zone, and backlog by year.
 *  - "Dashboard Data": the headline figures.
 * It can be read back with `parseTrackerWorkbook`.
 */
export async function writeMasterWorkbook(rows: MasterRow[], summary: Summary, opts: { asOf: IsoDate }): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'SONU';
  wb.created = new Date(`${opts.asOf}T00:00:00Z`);

  // --- Status ---------------------------------------------------------------------------------------------
  const st = wb.addWorksheet('Status', { views: [{ state: 'frozen', xSplit: 3, ySplit: 2 }] });
  st.getCell('A1').value = `Work request status as of ${opts.asOf} - generated by SONU (computed columns are values)`;
  st.getCell('A1').font = { bold: true, size: 13 };
  st.addRow([...TRACKER_COLUMNS]);
  styleHeader(st.getRow(2));
  for (const r of rows) {
    const line: (string | number | Date | null)[] = [
      isoToDate(r.dateRequested), isoToDate(r.dateTradeAssigned), r.wrCode, r.requestor, r.siteCode, r.siteName,
      r.buildingCode, r.buildingName, r.problemType, r.description, r.wrStatus, r.priority, r.workTeamCode,
      r.estimatedTotalCost, isoToDate(r.targetDate),
      r.status, r.fcRemarks,
      r.month, r.daysToBreach, r.tdStatus, r.kpi, isoToDate(r.rfeSubmittedOn), isoToDate(r.rfeApprovedOn),
      r.discipline, r.facility, r.zone, r.rfeStatus, r.daysSinceRequested, r.rfeTimeFrame,
    ];
    st.addRow(line);
  }
  // Dates: Date Work Requested (1), Date Trade Assigned (2), Agreed Target Date (15), RFE Submitted ON (22), RFE Approved on (23)
  for (const c of [1, 2, 15, 22, 23]) st.getColumn(c).numFmt = 'dd/mm/yyyy';
  st.getColumn(3).numFmt = '@';
  const widths = [13, 13, 13, 16, 9, 22, 10, 22, 11, 40, 20, 9, 14, 12, 13, 30, 30, 20, 10, 11, 13, 13, 13, 16, 22, 9, 18, 12, 38];
  widths.forEach((w, i) => (st.getColumn(i + 1).width = w));
  st.autoFilter = { from: { row: 2, column: 1 }, to: { row: 2, column: TRACKER_COLUMNS.length } };

  // --- Statistics: facility x status ------------------------------------------------------------------------
  const stat = wb.addWorksheet('Statistics');
  stat.getCell('A1').value = `Status by facility as of ${opts.asOf}`;
  stat.getCell('A1').font = { bold: true, size: 13 };
  const statuses = orderedStatuses(summary.byFacility.rows);
  stat.addRow(['Facility', ...statuses, 'Total']);
  styleHeader(stat.getRow(2));
  for (const f of summary.byFacility.columns) {
    stat.addRow([f, ...statuses.map((s) => summary.byFacility.cells[s]?.[f] ?? 0), summary.byFacility.columnTotals[f]]);
  }
  stat.addRow(['Total', ...statuses.map((s) => summary.byFacility.rowTotals[s] ?? 0), summary.byFacility.total]).font = { bold: true };
  stat.getColumn(1).width = 30;

  // --- Summary: discipline x zone, backlog by year ------------------------------------------------------------
  const sum = wb.addWorksheet('Summary');
  sum.getCell('A1').value = `Discipline by zone as of ${opts.asOf} (all outstanding work requests)`;
  sum.getCell('A1').font = { bold: true, size: 13 };
  const zones = summary.byZone.columns;
  sum.addRow(['Discipline', ...zones, 'Total']);
  styleHeader(sum.getRow(2));
  const dz = new Map<string, Map<string, number>>();
  for (const r of rows) {
    const m = dz.get(r.discipline) ?? new Map<string, number>();
    m.set(r.zone, (m.get(r.zone) ?? 0) + 1);
    dz.set(r.discipline, m);
  }
  for (const d of summary.byDiscipline.columns) {
    const m = dz.get(d) ?? new Map<string, number>();
    sum.addRow([d, ...zones.map((z) => m.get(z) ?? 0), summary.byDiscipline.columnTotals[d]]);
  }
  sum.addRow(['Total', ...zones.map((z) => summary.byZone.columnTotals[z] ?? 0), summary.totalOutstanding]).font = { bold: true };
  sum.addRow([]);
  const yh = sum.addRow(['Year requested', 'Outstanding', 'Backlog KPI']);
  styleHeader(yh);
  const backlogByYear = new Map<string, number>();
  for (const r of rows) {
    if (r.kpi !== 'Backlog KPI') continue;
    const y = r.dateRequested ? r.dateRequested.slice(0, 4) : 'No date';
    backlogByYear.set(y, (backlogByYear.get(y) ?? 0) + 1);
  }
  for (const [y, n] of Object.entries(summary.byYear)) sum.addRow([y, n, backlogByYear.get(y) ?? 0]);
  sum.getColumn(1).width = 24;

  // --- Dashboard Data -----------------------------------------------------------------------------------------
  const dash = wb.addWorksheet('Dashboard Data');
  dash.addRow(['Figure', 'Value']);
  styleHeader(dash.getRow(1));
  const add = (k: string, v: string | number) => dash.addRow([k, v]);
  add('As of', opts.asOf);
  add('Total outstanding', summary.totalOutstanding);
  add('Breached', summary.breached);
  add('Backlog KPI', summary.backlogKpi);
  add('Average age (days)', summary.averageAge);
  for (const [y, n] of Object.entries(summary.byYear)) add(`Year ${y}`, n);
  for (const [k, n] of Object.entries(summary.ageBuckets)) if (n) add(k, n);
  for (const [k, n] of Object.entries(summary.kpiSplit)) if (n) add(k, n);
  for (const [k, n] of Object.entries(summary.rfeTimeFrameSplit)) if (n) add(`RFE time frame: ${k}`, n);
  dash.getColumn(1).width = 30;

  return Buffer.from((await wb.xlsx.writeBuffer()) as ArrayBuffer);
}

/** Status rows in the order of the 15, then any other text. */
function orderedStatuses(found: string[]): string[] {
  const order = new Map(CONTRACTOR_STATUSES.map((s, i) => [s.name as string, i]));
  return [...found].sort((a, b) => (order.get(a) ?? 99) - (order.get(b) ?? 99) || a.localeCompare(b));
}

